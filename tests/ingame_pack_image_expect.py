def dds_header(w, h, fourcc):
    return (b"DDS " + struct.pack("<7I", 124, 0x81007, h, w, 0, 0, 0) + bytes(44) + struct.pack("<4I", 32, 4, fourcc, 0)
            + bytes(16) + struct.pack("<5I", 0x1000, 0, 0, 0, 0))


def dx10_header(w, h, dxgi):
    return dds_header(w, h, struct.unpack("<I", b"DX10")[0]) + struct.pack("<5I", dxgi, 3, 0, 1, 0)


