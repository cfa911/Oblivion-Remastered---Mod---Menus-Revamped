BANDS = {"L": 1, "LA": 2, "RGB": 3, "RGBA": 4}


def lcg(seed, n):
    x, out = seed, bytearray()
    for _ in range(n):
        x = (x * 1103515245 + 12345) & 0x7FFFFFFF
        out.append((x >> 16) & 255)
    return bytes(out)


def img(mode, w, h, seed):
    return Image.frombytes(mode, (w, h), lcg(seed, w * h * BANDS[mode]))


def few(w, h, seed):
    """An RGBA image of a few colours (getcolors)."""
    palette = [(0, 0, 0, 0), (255, 0, 0, 255), (12, 200, 7, 128), (12, 200, 7, 129), (255, 255, 255, 255), (1, 2, 3, 4)]
    picks = lcg(seed, w * h)
    return Image.frombytes("RGBA", (w, h), b"".join(bytes(palette[p % len(palette)]) for p in picks))


lines = [f"// Generated by tests/ingame_pack_image_expect.py with Pillow {PIL.__version__}. Do not edit."]


def emit(name, data):
    data = bytes(data)
    body = ",".join(str(b) for b in data) or "0"
    lines.append(f"static const std::uint8_t k{name}[] = {{{body}}};")
    lines.append(f"static const std::size_t k{name}Size = {len(data)};")


def emit_image(name, im):
    emit(name, im.tobytes())


def png_bytes(raw_rows, w, h, colour_type, filters):
    """A PNG with the given per-row filter types (0..4), so the decoder sees every filter."""
    bpp = {0: 1, 2: 3, 4: 2, 6: 4}[colour_type]
    stride = w * bpp
    prev = bytes(stride)
    out = bytearray()
    for y in range(h):
        row = raw_rows[y * stride:(y + 1) * stride]
        f = filters[y % len(filters)]
        enc = bytearray()
        for i in range(stride):
            a = row[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if f == 0:
                p = 0
            elif f == 1:
                p = a
            elif f == 2:
                p = b
            elif f == 3:
                p = (a + b) // 2
            else:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                p = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
            enc.append((row[i] - p) & 255)
        out.append(f)
        out += enc
        prev = row

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", w, h, 8, colour_type, 0, 0, 0)
    z = zlib.compress(bytes(out), 9)
    # two IDAT chunks: the decoder must join them
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", z[:7]) + chunk(b"IDAT", z[7:]) + chunk(b"IEND", b"")


