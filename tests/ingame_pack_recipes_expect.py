"""Oracle for tests/ingame_pack_recipes_tests.cpp (In-game Pack Builder Phase 3c): bakes image recipes of
tools/pack_builder/pipeline.py on a synthetic stock texture and writes their SHA-256 (or skip reason) into
tests/ingame_pack_recipes_expect.inc. The C++ test builds the same stock (the same pixel formula, EncodeBc) and must match.

    python tests/ingame_pack_recipes_expect.py      (Pillow 13.0.0; no -I: Pillow lives in the user site)
"""
import hashlib
import sys
import tempfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from pack_builder import pipeline  # noqa: E402

W, H = 64, 32


def pixel(x, y):   # the same formula as Synthetic() in the C++ test
    return ((x * 7 + y * 3) % 256, (x * x + y * 5) % 256, (y * 9 + x) % 256, 255 if (x + y) % 7 else 90)


VALUES = {
    "parchmentDark": [8.0, 8.0, 8.0], "parchmentLight": [33.0, 33.0, 33.0], "panel": [28.0, 28.0, 28.0], "frame": [12.0, 12.0, 12.0],
    "pattern": [201.0, 160.0, 75.5], "detailsPage": 0.01, "effectIcon": [230.0, 190.0, 90.0], "menuTitle": [80.0, 120.0, 210.0],
    "enchantingFrame": [150.0, 160.0, 180.0], "altarPaper": [40.0, 41.0, 44.0], "listHighlight": [120.0, 90.0, 40.0],
    "previewFrameLight": [200.0, 190.0, 170.0], "previewFrameDark": [10.0, 12.0, 14.0], "enchantedDot": [90.0, 200.0, 255.0],
    "alchemyMetal": [180.0, 140.0, 60.0], "alchemyStone": [90.0, 95.0, 92.0], "tabPaperDark": [20.0, 20.0, 22.0],
    "tabPaperLight": [60.0, 60.0, 64.0], "tabGlyph": [240.0, 238.0, 230.0],
}

CASES = ["parchment", "parchment:enchanting", "paper_scale:0.9", "mask_peak:120", "smooth_grain:1.5:0.6", "page_grain:3:7.5",
         "paper_invert:1.5", "paper_invert:3:0.7", "page_invert:3:0.7", "details_invert:3", "details_smooth:1.5:0.6", "gray_smooth:1.5",
         "band_lines:1.6", "line_tint:1.6", "laurel_tint", "laurel_tint:effectIcon:42", "flat_alpha:listHighlight:0.35",
         "frame_metal:enchantingFrame", "altar_panel:enchantingFrame", "altar_panel_invert:enchantingFrame:1.5",
         "altar_panel_invert:enchantingFrame:1.5:12:25", "popup_panel:0.05:0.03", "popup_paper:0.6", "popup_paper:0", "quest_icon",
         "ink_gold", "white_backing", "skill_ring", "charcoal:glyph", "charcoal:emblem", "charcoal:paper", "charcoal:laurel",
         "charcoal:enchanting", "charcoal:nope", "details_page", "gray", "preview_frame", "enchanted_dot", "alchemy", "skill_card:3"]


def main():
    work = Path(tempfile.mkdtemp(prefix="mr-recipes-expect-"))
    image = Image.new("RGBA", (W, H))
    image.putdata([pixel(x, y) for y in range(H) for x in range(W)])
    dds = work / "T_Synthetic.dds"
    image.save(dds, pixel_format="DXT5")
    head = pipeline.header_size(dds.read_bytes())
    lines = ["// generated by tests/ingame_pack_recipes_expect.py: {recipe, sha256 of the body or \"\", skip reason}"]
    for name in CASES:
        try:
            out = pipeline.recipe(name)[2](dds, VALUES, work, None)
            lines.append(f'{{ "{name}", "{hashlib.sha256(out[head:]).hexdigest()}", "" }},')
        except Exception as error:
            reason = str(error) if isinstance(error, pipeline.SkipAsset) else f"{type(error).__name__}: {error}"
            lines.append(f'{{ "{name}", "", "{reason}" }},')
    (Path(__file__).with_name("ingame_pack_recipes_expect.inc")).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


main()
