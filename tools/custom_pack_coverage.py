"""The Custom pack coverage page: every asset Dark Mode UI (Nexus 3317) replaces, by menu, with its state in our pack.

Usage:
  python tools/custom_pack_coverage.py --textures <textures-list.txt> --widgets <text-edits-list.txt> --out <page.md>
                                       [--menus tools/menus] [--notes tools/coverage_notes.json]

The two lists are `retoc list` output of Dark Mode UI's containers (names only: never copy, ship or edit that mod's files).
Status of each listed asset: "in pack" (a row in tools/menus/*.json, with its recipe), "not planned" (coverage_notes.json
"not_planned": exact asset path -> reason), else "later" (a coverage_notes.json "later" reason when a path fragment matches;
widget and data assets: literal patch only, owner decision 20). Menus come from the "menus" rules (path fragment -> menu,
first match), else the asset's folder. Our own pack assets Dark Mode UI does not touch get their own section.
Rerun after each batch; the KB keeps the page in mods/menus-revamped/evidence/custom-pack-coverage.md.
"""
import argparse
import json
import re
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
PATH = re.compile(r"\.\./\.\./\.\./OblivionRemastered/Content/(\S+)\.uasset")
LITERAL = "literal patch only (decision 20: no whole blueprints)"


def listed(path):
    """Asset paths (under Content, no extension) of a `retoc list` file, in file order, once each."""
    seen = []
    for line in Path(path).read_text(encoding="utf-8", errors="replace").splitlines():
        m = PATH.search(line)
        if m and m.group(1) not in seen:
            seen.append(m.group(1))
    return seen


def pack_rows(folder):
    rows = {}
    for path in sorted(Path(folder).glob("*.json")):
        for row in json.loads(path.read_text(encoding="utf-8")).get("assets", []):
            rows[row["asset"]] = row["recipe"]
    return rows


def menu_of(asset, rules):
    for fragment, menu in rules:
        if fragment in asset:
            return menu
    return asset.rsplit("/", 2)[-2] if "/" in asset else "Other"


def status(asset, widget, rows, notes):
    if asset in rows:
        return f"in pack (`{rows[asset]}`)"
    if asset in notes.get("not_planned", {}):
        return "not planned: " + notes["not_planned"][asset]
    reason = next((r for fragment, r in notes.get("later", {}).items() if fragment in asset), "")
    if widget:
        reason = LITERAL + (f"; {reason}" if reason else "")
    return "later" + (f": {reason}" if reason else "")


def render(textures, widgets, rows, notes):
    rules = notes.get("menus", [])
    kinds = {a: "texture" for a in textures} | {a: "widget/data" for a in widgets}
    groups = {}
    for asset, kind in kinds.items():
        groups.setdefault(menu_of(asset, rules), []).append((asset, kind))
    in_tex = sum(a in rows for a in textures)
    in_wid = sum(a in rows for a in widgets)
    out = ["# Custom pack coverage against Dark Mode UI", "",
           "Generated by `custom_pack_coverage.py` (Menus Revamped source, tools folder) from Dark Mode UI's saved asset lists",
           "(names only) and the builder data files; rerun it after each batch instead of editing this page by hand.", "",
           f"- **Textures: {in_tex} of {len(textures)} textures in pack.**",
           f"- **Widget and data assets: {in_wid} of {len(widgets)} widget/data assets in pack** (colour literals patched in place).",
           f"- Our own pack assets Dark Mode UI does not touch: {sum(a not in kinds for a in rows)}.", ""]
    for menu in sorted(groups):
        items = sorted(groups[menu])
        done = sum(a in rows for a, _ in items)
        out += [f"## {menu}", "", f"{done} of {len(items)} in pack.", "", "| Asset | Kind | Path | Status |", "|---|---|---|---|"]
        out += [f"| `{Path(a).name}` | {k} | {a.rsplit('/', 1)[0]} | {status(a, k != 'texture', rows, notes)} |" for a, k in items]
        out.append("")
    own = sorted(a for a in rows if a not in kinds)
    out += ["## Our own assets (not in Dark Mode UI)", "", "| Asset | Kind | Path | Status |", "|---|---|---|---|"]
    out += [f"| `{Path(a).name}` | {'texture' if a.startswith('Art/') else 'widget/material'} | {a.rsplit('/', 1)[0]} | in pack (`{rows[a]}`) |"
            for a in own]
    return "\n".join(out) + "\n"


def main(argv=None):
    cli = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    cli.add_argument("--textures", type=Path, required=True)
    cli.add_argument("--widgets", type=Path, required=True)
    cli.add_argument("--menus", type=Path, default=TOOLS / "menus")
    cli.add_argument("--notes", type=Path, default=TOOLS / "coverage_notes.json")
    cli.add_argument("--out", type=Path, required=True)
    a = cli.parse_args(argv)
    notes = json.loads(a.notes.read_text(encoding="utf-8")) if a.notes.is_file() else {}
    text = render(listed(a.textures), listed(a.widgets), pack_rows(a.menus), notes)
    a.out.write_text(text, encoding="utf-8")
    print(text.split("\n\n", 2)[1] if "\n\n" in text else text[:200])


if __name__ == "__main__":
    main()
